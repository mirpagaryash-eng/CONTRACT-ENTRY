import { test, expect } from '@playwright/test';
import { mkdir } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { join } from 'node:path';
import { createApp } from '../server/app.js';

const executablePath = process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE || (existsSync('/usr/bin/chromium') ? '/usr/bin/chromium' : undefined);
const artifactDir = process.env.ARTIFACT_DIR || 'test-results/screenshots';
test.use({ launchOptions: { ...(executablePath ? { executablePath } : {}), args: ['--no-sandbox'] } });
let app;
let base;

test.beforeAll(async () => {
  app = createApp({ dbPath: ':memory:', env: {}, fetchImpl: async () => { throw new Error('External messaging must not run in UI tests.'); } });
  await new Promise(resolve => app.server.listen(0, '127.0.0.1', resolve));
  base = `http://127.0.0.1:${app.server.address().port}`;
  await mkdir(artifactDir, { recursive: true });
});
test.afterAll(async () => { await app?.close(); });

test('owner records, corrects and shares an advance; worker view stays private and read-only', async ({ page, browser }) => {
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto(base);
  await page.getByLabel('Your name', { exact: false }).fill('Yash');
  await page.getByLabel('Business name', { exact: false }).fill('Sai Services');
  await page.getByLabel('Your mobile number', { exact: false }).fill('+12025550100');
  await page.getByLabel('Choose a password', { exact: false }).fill('Test-owner-password-123');
  await page.getByRole('button', { name: 'Create my register' }).click();
  await expect(page.getByRole('heading', { name: 'Your register, at a glance.' })).toBeVisible();
  await page.getByRole('button', { name: 'Add worker', exact: true }).click();
  await page.getByLabel('Worker’s name').fill('Abhay');
  await page.getByLabel('WhatsApp number').fill('+12025550101');
  await page.getByRole('dialog').getByLabel('Contract', { exact: false }).selectOption('SANJYOT');
  await page.getByRole('button', { name: 'Add worker', exact: true }).last().click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.getByRole('button', { name: 'Record advance', exact: true }).first().click();
  await page.getByLabel('Advance amount in rupees').fill('1000.50');
  await page.getByLabel('Note', { exact: false }).fill('Personal advance');
  await page.getByRole('button', { name: 'Save advance', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Advance saved' })).toBeVisible();
  const whatsapp = page.getByRole('link', { name: 'Open WhatsApp' });
  await expect(whatsapp).toHaveAttribute('href', /^https:\/\/wa\.me\/12025550101\?text=/);
  // Inspect the prepared link only; never open WhatsApp or send a message.
  await page.getByRole('button', { name: 'Close dialog' }).click();
  await expect(page.getByText('₹1,000.50').first()).toBeVisible();
  await page.getByRole('button', { name: 'Edit advance for Abhay' }).first().click();
  await expect(page.getByRole('dialog').locator('select[name=workerId]')).toBeDisabled();
  await page.getByLabel('Advance amount in rupees').fill('1250.75');
  await page.getByLabel('Payment method').selectOption('online');
  await page.getByLabel('Note', { exact: false }).fill('Corrected advance');
  await page.getByRole('button', { name: 'Save changes', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Advance saved' })).toBeVisible();
  await page.getByRole('button', { name: 'Close dialog' }).click();
  await expect(page.getByText('₹1,250.75').first()).toBeVisible();
  const dashboard = await (await page.request.get(`${base}/api/dashboard`)).json();
  expect(dashboard.advances).toHaveLength(1);
  expect(dashboard.advances[0].revision).toBe(2);
  const fixtureHeaders = { 'X-CSRF-Token': dashboard ? (await (await page.request.get(`${base}/api/session`)).json()).csrfToken : '' };
  const secondWorker = (await (await page.request.post(`${base}/api/workers`, { headers: fixtureHeaders, data: { name: 'Ravi Kumar', phone: '+12025550102', contract: 'TECHNOEDGE', whatsappConsent: false } })).json()).worker;
  await page.request.post(`${base}/api/advances`, { headers: fixtureHeaders, data: { workerId: secondWorker.id, amount: '2000', date: dashboard.today, method: 'cash', note: 'Family expenses' } });
  await page.request.post(`${base}/api/advances`, { headers: fixtureHeaders, data: { workerId: secondWorker.id, amount: '500', date: dashboard.today, method: 'online', note: 'Travel advance' } });
  await page.reload();
  await expect(page.getByRole('heading', { name: 'Your register, at a glance.' })).toBeVisible();
  await page.screenshot({ path: join(artifactDir, 'hisab-desktop.png'), fullPage: true, animations: 'disabled' });
  const workerUrl = `${base}/w/${dashboard.workers[0].shareToken}`;
  const workerContext = await browser.newContext({ viewport: { width: 390, height: 844 } });
  const workerPage = await workerContext.newPage();
  await workerPage.goto(workerUrl);
  await expect(workerPage.getByRole('heading', { name: 'Hello, Abhay.' })).toBeVisible();
  await expect(workerPage.getByText('₹1,250.75').first()).toBeVisible();
  await expect(workerPage.getByText('Corrected advance')).toBeVisible();
  await expect(workerPage.getByRole('button', { name: /edit|save|record/i })).toHaveCount(0);
  expect((await workerPage.request.get(`${base}/api/dashboard`)).status()).toBe(401);
  await workerPage.screenshot({ path: join(artifactDir, 'hisab-worker.png'), fullPage: true, animations: 'disabled' });
  const downloadEvent = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export CSV' }).click();
  const download = await downloadEvent;
  expect(download.suggestedFilename()).toMatch(/hisab-advances/);
  await page.setViewportSize({ width: 390, height: 844 });
  if (await page.getByRole('button', { name: 'Dismiss', exact: true }).count()) await page.getByRole('button', { name: 'Dismiss', exact: true }).click();
  await expect.poll(() => page.locator('.sidebar').evaluate(element => element.getBoundingClientRect().right)).toBeLessThanOrEqual(0);
  await page.screenshot({ path: join(artifactDir, 'hisab-mobile.png'), fullPage: true, animations: 'disabled' });
  expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false);
  await expect(page.locator('.mobile-message-button').first()).toBeVisible();
  await page.getByRole('button', { name: 'Open menu' }).click();
  await page.getByRole('button', { name: 'History', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'A record of every change.' })).toBeVisible();
  await expect(page.getByText(/advance corrected from/)).toBeVisible();
  await page.getByRole('button', { name: 'Open menu' }).click();
  await page.getByRole('button', { name: 'All advances', exact: true }).click();
  await page.getByRole('button', { name: 'Edit advance for Abhay' }).click();
  await page.getByRole('button', { name: 'Cancel this entry instead' }).click();
  await page.getByLabel('Reason for cancellation').fill('Duplicate entry recorded by mistake');
  await page.getByRole('button', { name: 'Confirm cancellation' }).click();
  await expect(page.getByRole('heading', { name: 'Entry cancelled' })).toBeVisible();
  await expect(page.locator('.whatsapp-preview p')).toContainText(/cancelled/i);
  await expect(workerPage.getByRole('heading', { name: 'Advance cancelled' })).toBeVisible({ timeout: 12000 });
  await expect(workerPage.getByText('Reason: Duplicate entry recorded by mistake')).toBeVisible();
  const finalDashboard = await (await page.request.get(`${base}/api/dashboard`)).json();
  expect(finalDashboard.advances.find(a => a.workerName === 'Abhay').voided).toBe(true);
  expect(finalDashboard.workers.find(w => w.name === 'Abhay').monthTotalPaise).toBe(0);
  await workerContext.close();
  expect(errors).toEqual([]);
});
